#!/usr/bin/env python3
"""Reproduce numerical comparisons. Benchmarks enter ONLY this reporting layer."""
import argparse,csv,io,json,pathlib,subprocess,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--exe',default='build/pcd');p.add_argument('--check',action='store_true');a=p.parse_args()
exe=(ROOT/a.exe).resolve()
if sys.platform=='win32' and not exe.exists():exe=exe.with_suffix('.exe')
sys.path.insert(0,str(ROOT))
from literature.average import calculate, artifact_contents
b=json.loads((ROOT/'data/benchmarks.json').read_text())
averages=calculate()
methods=['original','hj9','bp12','dlog-pade'];values={};outputs={}
for method in methods:
 out=subprocess.check_output([str(exe),'--method',method],text=True)
 outputs[method]=out
 values[method]={(int(r['q']),int(r['d'])):float(r['p_model']) for r in csv.DictReader(io.StringIO(out))}
rows=[]
for method, vals in values.items():
 for (q,d),v in sorted(vals.items()):
  refs=[r for r in b['benchmarks'] if (r['q'],r['d'])==(q,d)] or [None]
  for ref in refs:
   rows.append(dict(q=q,d=d,method=method,p_model=format(v,'.17g'),p_reference='' if ref is None else format(ref['p_value'],'.17g'),reference_uncertainty='' if ref is None else ref.get('p_uncertainty',''),relative_error_percent='' if ref is None else format(100*(v/ref['p_value']-1),'.12g'),source_id='' if ref is None else ref['source_id'],selected_reference='' if ref is None else ref['selected']))
buf=io.StringIO();w=csv.DictWriter(buf,fieldnames=list(rows[0]),lineterminator='\n');w.writeheader();w.writerows(rows)
def weighted_reference(key):
 ref=averages.get(key)
 if ref is None or ref['p_mean'] is None:return '—'
 return f'{float(ref["p_mean"]):.10f}'
# The front page compares the original formula with a descriptive literature mean.
lines=['| q | d | PCD | Weighted literature | Δ (%) |','|---:|---:|---:|---:|---:|']
for (q,d),v in sorted(values['original'].items()):
 ref=averages.get((q,d));mean=None if ref is None else ref['p_mean']
 err='—' if mean is None else f'{100*(v/float(mean)-1):+.5f}'
 if d==2:err='0'
 lines.append(f'| {q} | {d} | {v:.8f} | {weighted_reference((q,d))} | {err} |')
main='\n'.join(lines)
readme=(ROOT/'docs/README.template.md').read_text().replace('<!-- ORIGINAL_TABLE -->',main)
ext=['# Additional estimators and complete benchmark comparison','','Generated by `scripts/make_tables.py`; all estimators are run by the C++ executable. No fitting to benchmark thresholds occurs. The [weighted literature references](../literature/) are computed separately from published estimates and nominal errors.','','These methods are distinct approximations, not a hierarchy of guarantees. High-dimensional truncations can deteriorate badly at small d; their failure is retained here. A quoted Monte Carlo or series uncertainty is not a rigorous enclosure. Empty cells mean unsupported method or no verified reference.','','| q | d | Original | HJ9 | BP12 | Dlog–Padé | Weighted literature |','|---:|---:|---:|---:|---:|---:|---:|']
for key in sorted(values['original']):
 q,d=key;nums=[f'{values[m][key]:.10f}' if key in values[m] else '—' for m in methods]
 ext.append(f'| {q} | {d} | '+ ' | '.join(nums)+' | '+weighted_reference(key)+' |')
ext+=['','## Original source conventions','','| Source | Variables / estimate type | Reference |','|---|---|---|']
for sid,source in b['sources'].items():ext.append(f'| {sid} | {source["type"]} | [{source["title"]}]({source["url"]}), {source["location"]} |')
ext+=['','## All original benchmark values','','The earlier selected/alternative labels below are retained for provenance. The weighted mean uses the explicit [averaging policy](../literature/policy.json), not these labels.','','| q | d | Printed estimate | Variable | Earlier selection | Source |','|---:|---:|---|---|---|---|']
for ref in b['benchmarks']:ext.append(f'| {ref["q"]} | {ref["d"]} | {ref["original_printed"]} | {ref["original_variable"]} | {"yes" if ref["selected"] else "alternative"} | {ref["source_id"]} |')
ext+=['','The full [comparison.csv](../data/comparison.csv) compares every supported estimator with every sourced benchmark, including alternative published estimates. Original uncertainties and conversion endpoints are retained in [benchmarks.json](../data/benchmarks.json).','','Reviewed 2026-10-25. Coverage is the set of primary sources located in this research pass; it is not a claim to include every published estimate.','']
artifacts={'README.md':readme,'docs/numerical-comparison.md':'\n'.join(ext),'data/comparison.csv':buf.getvalue(),'data/model_values.csv':outputs['original']}
artifacts.update(artifact_contents())
for method in ['hj9','bp12','dlog-pade']:artifacts[f'data/{method}_values.csv']=outputs[method]
for name,content in artifacts.items():
 target=ROOT/name
 if a.check:
  # Floating point formatting may vary in the final printed ulp across compilers.
  if not target.exists():sys.exit('MISSING '+name)
  if target.read_text().replace('\r\n','\n')!=content.replace('\r\n','\n'):sys.exit('REGENERATION_MISMATCH '+name)
 else:target.write_text(content)
print('TABLE_REPRODUCTION=PASS' if a.check else 'TABLES_GENERATED=PASS')
